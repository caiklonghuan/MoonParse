#!/usr/bin/env node

import { copyFile, mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import { dirname, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ids = ["json", "python", "moonbit"];
const outputPath = resolve(root, "grammars/language_packs_generated.mbt");
const websiteOutputPath = resolve(root, "website/src/data/languagePackResources.js");
const lspOutputPath = resolve(root, "lsp/src/language-pack-resources.ts");
const write = process.argv.includes("--write");

function posix(path) {
  return path.split(sep).join("/");
}

async function filesUnder(dir) {
  const result = [];
  async function visit(current) {
    for (const entry of await readdir(current, { withFileTypes: true })) {
      const path = resolve(current, entry.name);
      if (entry.isDirectory()) await visit(path);
      else if (entry.isFile()) result.push(path);
    }
  }
  await visit(dir);
  return result.sort();
}

const lines = [
  "// Generated by scripts/embed-language-packs.mjs. DO NOT EDIT.",
  "",
];
const websiteResources = {};

for (const id of ids) {
  const packRoot = resolve(root, "languages", id);
  const manifest = await readFile(resolve(packRoot, "language-pack.json"), "utf8");
  const resources = [];
  for (const path of await filesUnder(packRoot)) {
    const rel = posix(relative(packRoot, path));
    if (rel === "language-pack.json" || rel === "README.md") continue;
    resources.push([rel, await readFile(path, "utf8")]);
  }
  const manifestValue = JSON.parse(manifest);
  const resourceMap = Object.fromEntries(resources);
  websiteResources[id] = {
    manifest: manifestValue,
    grammar: resourceMap[manifestValue.grammar.path],
    highlightQuery: manifestValue.queries?.highlights ? resourceMap[manifestValue.queries.highlights] : null,
    localsQuery: manifestValue.queries?.locals ? resourceMap[manifestValue.queries.locals] : null,
    bindingsQuery: manifestValue.queries?.bindings ? resourceMap[manifestValue.queries.bindings] : null,
    foldingQuery: manifestValue.queries?.folding ? resourceMap[manifestValue.queries.folding] : null,
  };
  lines.push(`///|`, `let embedded_${id}_manifest : String = ${JSON.stringify(manifest)}`, "");
  resources.forEach(([path, text], index) => {
    lines.push(`///|`, `let embedded_${id}_file_${index} : String = ${JSON.stringify(text)}`, "");
  });
  lines.push(
    "///|",
    `pub fn embedded_${id}_pack_source() -> @languagepack.LanguagePackSource {`,
    "  let files : Map[String, Bytes] = Map::new()",
  );
  resources.forEach(([path], index) => {
    lines.push(`  files[${JSON.stringify(path)}] = @utf8.encode(embedded_${id}_file_${index})`);
  });
  lines.push(
    `  @languagepack.LanguagePackSource::new(embedded_${id}_manifest, files)`,
    "}",
    "",
  );
}

// The final empty line already gives the MoonBit formatter's single trailing LF.
const expected = lines.join("\n");
const expectedWebsite = `// Generated by scripts/embed-language-packs.mjs. DO NOT EDIT.\nexport const LANGUAGE_PACK_RESOURCES = ${JSON.stringify(websiteResources, null, 2)}\n`;
const expectedLsp = `// Generated by scripts/embed-language-packs.mjs. DO NOT EDIT.\nexport const LANGUAGE_PACK_RESOURCES = ${JSON.stringify(websiteResources, null, 2)} as const;\n`;
const legacyManifestPath = resolve(root, "grammars/manifest.json");
const legacyManifest = JSON.parse(await readFile(legacyManifestPath, "utf8"));
for (const language of legacyManifest.languages) {
  const pack = websiteResources[language.id]?.manifest;
  if (!pack) continue;
  language.name = pack.name;
  language.status = pack.maturity;
  language.extensions = pack.extensions;
  language.entryRule = pack.entryRule;
  language.grammar = `../languages/${pack.id}/${pack.grammar.path}`;
  language.corpus = `../languages/${pack.id}/${pack.corpus.directory}`;
  language.highlightQuery = pack.queries?.highlights ? "pack" : undefined;
  if (pack.queries?.locals) language.localsQuery = "pack";
  else delete language.localsQuery;
}
const expectedLegacyManifest = `${JSON.stringify(legacyManifest, null, 2)}\n`;

if (write) {
  await mkdir(dirname(outputPath), { recursive: true });
  await writeFile(outputPath, expected, "utf8");
  await writeFile(websiteOutputPath, expectedWebsite, "utf8");
  await writeFile(lspOutputPath, expectedLsp, "utf8");
  await writeFile(legacyManifestPath, expectedLegacyManifest, "utf8");
  for (const id of ids) {
    await copyFile(
      resolve(root, `languages/${id}/grammar/main.grammar`),
      resolve(root, `grammars/${id}.grammar`),
    );
  }
  console.log("Embedded language packs and legacy grammar mirrors updated.");
} else {
  const errors = [];
  const actual = await readFile(outputPath, "utf8").catch(() => "");
  if (actual.replace(/\r\n/g, "\n") !== expected) errors.push("grammars/language_packs_generated.mbt");
  const actualWebsite = await readFile(websiteOutputPath, "utf8").catch(() => "");
  if (actualWebsite.replace(/\r\n/g, "\n") !== expectedWebsite) errors.push("website/src/data/languagePackResources.js");
  const actualLsp = await readFile(lspOutputPath, "utf8").catch(() => "");
  if (actualLsp.replace(/\r\n/g, "\n") !== expectedLsp) errors.push("lsp/src/language-pack-resources.ts");
  const actualLegacyManifest = await readFile(legacyManifestPath, "utf8").catch(() => "");
  if (actualLegacyManifest.replace(/\r\n/g, "\n") !== expectedLegacyManifest) errors.push("grammars/manifest.json");
  for (const id of ids) {
    const [canonical, mirror] = await Promise.all([
      readFile(resolve(root, `languages/${id}/grammar/main.grammar`), "utf8"),
      readFile(resolve(root, `grammars/${id}.grammar`), "utf8"),
    ]);
    if (canonical.replace(/\r\n/g, "\n") !== mirror.replace(/\r\n/g, "\n")) {
      errors.push(`grammars/${id}.grammar`);
    }
  }
  if (errors.length) {
    console.error("Language pack embedded resources are stale:");
    errors.forEach((path) => console.error(`- ${path}`));
    process.exit(1);
  }
  console.log("Language pack embedded resources are fresh.");
}
